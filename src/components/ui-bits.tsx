import { useEffect, useState } from "react";
import { Check, Copy, ShieldAlert, FlaskConical } from "lucide-react";

export function SimBadge() {
  return (
    <span className="inline-flex items-center gap-1 rounded-full bg-accent/25 px-2.5 py-0.5 text-xs font-semibold text-foreground">
      <FlaskConical className="h-3 w-3" /> Simulated AI
    </span>
  );
}

export function Disclaimer() {
  return (
    <div className="flex gap-3 rounded-xl border border-accent/50 bg-accent/10 p-3 text-xs text-muted-foreground">
      <ShieldAlert className="h-4 w-4 shrink-0 text-foreground" />
      <p>
        <strong className="text-foreground">Responsible AI:</strong> Outputs here are generated by simulated, rule-based logic in your browser — no real AI model or web access is used. They may contain errors or omissions; review and verify before professional use.
      </p>
    </div>
  );
}

export function CopyButton({ text }: { text: string }) {
  const [ok, setOk] = useState(false);
  return (
    <button
      className="btn btn-ghost px-2.5 py-1.5 text-xs"
      onClick={() => {
        navigator.clipboard.writeText(text);
        setOk(true);
        setTimeout(() => setOk(false), 1500);
      }}
    >
      {ok ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />} {ok ? "Copied" : "Copy"}
    </button>
  );
}

export function EditableOutput({ value, rows = 16 }: { value: string; rows?: number }) {
  const [text, setText] = useState(value);
  useEffect(() => setText(value), [value]);
  return (
    <div className="space-y-2">
      <div className="flex items-center justify-between">
        <span className="text-xs text-muted-foreground">Editable output</span>
        <CopyButton text={text} />
      </div>
      <textarea className="field font-mono text-xs leading-relaxed" rows={rows} value={text} onChange={(e) => setText(e.target.value)} />
    </div>
  );
}

export function PageHeader({ title, subtitle }: { title: string; subtitle: string }) {
  return (
    <div className="mb-6 flex flex-wrap items-end justify-between gap-3">
      <div>
        <h1 className="text-3xl font-semibold">{title}</h1>
        <p className="mt-1 text-sm text-muted-foreground">{subtitle}</p>
      </div>
      <SimBadge />
    </div>
  );
}
